/* Template values, used by Windows when the OTP gives no calibration. */
#define TEMPLATE_TCODE_SEC4 (0x0080)
#define TEMPLATE_FDT_DELTA  (0x15)

#define TAG_TCODE     (0x005c)
#define TAG_FDT_DELTA (0x0082)

void
goodix55b4_calib_from_otp (const guint8 *otp, gsize len, Goodix55b4Calib *c)
{
  guint8 code, check;
  guint tcode, scaled, delta;

  memset (c, 0, sizeof (*c));
  c->tcode = TEMPLATE_TCODE_SEC4;
  c->fdt_delta = TEMPLATE_FDT_DELTA;

  if (!otp || len < 24)
    return;
  code = otp[22];
  check = otp[23];
  /* byte 23 is the complement of byte 22 */
  if (code == 0 || code + check != 0xff)
    return;

  tcode = ((code >> 4) + 1) << 4;
  scaled = (guint16) ((((code & 0x0f) + 2) * 0x6400u) / tcode);
  delta = (scaled / 3) >> 4;
  /* Windows takes these as they are; refuse values no real unit has
   * (the delta must fit the 8-bit FDT table with room for readings). */
  if (delta < 4 || delta > 0x40)
    return;

  c->from_otp = TRUE;
  c->tcode = tcode;
  c->fdt_delta = delta;
}

/* Set every entry `tag` of config section `section`. */
static void
set_tag (guint8 *cfg, guint section, guint16 tag, guint16 value)
{
  guint base = cfg[1 + section * 2];
  guint size = cfg[2 + section * 2];

  for (guint e = base; e + 4 <= base + size && e + 4 <= GOODIX55B4_CONFIG_SIZE - 2; e += 4)
    if ((cfg[e] | (cfg[e + 1] << 8)) == tag)
      {
        cfg[e + 2] = value & 0xff;
        cfg[e + 3] = value >> 8;
      }
}

void
goodix55b4_config_build (const Goodix55b4Calib *c, guint8 out[GOODIX55B4_CONFIG_SIZE])
{
  guint16 sum = 0xa5a5;

  memcpy (out, base_config, GOODIX55B4_CONFIG_SIZE);

  if (c->from_otp)
    {
      set_tag (out, 2, TAG_TCODE, c->tcode);
      set_tag (out, 4, TAG_TCODE, c->tcode);
    }
  else
    {
      set_tag (out, 4, TAG_TCODE, TEMPLATE_TCODE_SEC4);
    }
  set_tag (out, 2, TAG_FDT_DELTA, (c->fdt_delta << 8) | 0x80);

  for (guint i = 0; i < GOODIX55B4_CONFIG_SIZE - 2; i += 2)
    sum += out[i] | (out[i + 1] << 8);
  sum = -sum;
  out[GOODIX55B4_CONFIG_SIZE - 2] = sum & 0xff;
  out[GOODIX55B4_CONFIG_SIZE - 1] = sum >> 8;
}
